#!/usr/bin/env node
/**
 * Remove `aps-environment` from the generated iOS entitlements.
 *
 * Why this exists
 * ---------------
 * The `expo-notifications` config plugin unconditionally adds `aps-environment`
 * for remote push. A free Apple Personal Team does not support the Push
 * Notifications capability at all, so Xcode rejects the build at the signing
 * step:
 *
 *   Personal development teams, including "...", do not support the
 *   Push Notifications capability.
 *
 * This project does not use remote push. Every notification is a LOCAL
 * notification raised on-device, and every expo-notifications API we call is a
 * local-notification API:
 *
 *   setNotificationHandler                    foreground banner presentation
 *   getLastNotificationResponseAsync          cold-start deep link
 *   addNotificationResponseReceivedListener   notification tap handling
 *
 * So `aps-environment` has no reason to be present, and removing it makes the
 * build sign successfully with a free team.
 *
 * When it runs
 * ------------
 * `ios/` is regenerated by `expo prebuild` on every run (and is gitignored), so
 * editing the file by hand is pointless — the next prebuild discards it. This
 * script is therefore chained after `prebuild` and before `run:ios` in
 * package.json, so it re-applies immediately after each generation.
 *
 * If this project ever moves to a paid team and uses real remote push, drop
 * this script from the npm script chain.
 */
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'

const IOS_DIR = join(process.cwd(), 'ios')
const KEY = 'aps-environment'

if (!existsSync(IOS_DIR)) {
  console.log('[strip-aps] no ios/ directory — skipping (run before prebuild).')
  process.exit(0)
}

/** Find every *.entitlements under ios/, ignoring Pods and build output. */
function findEntitlements(dir) {
  const found = []
  for (const name of readdirSync(dir)) {
    if (name === 'Pods' || name === 'build') continue
    const path = join(dir, name)
    if (statSync(path).isDirectory()) found.push(...findEntitlements(path))
    else if (name.endsWith('.entitlements')) found.push(path)
  }
  return found
}

const files = findEntitlements(IOS_DIR)

if (files.length === 0) {
  console.log('[strip-aps] no .entitlements files found.')
  process.exit(0)
}

let changed = 0

for (const file of files) {
  const before = readFileSync(file, 'utf8')

  // Remove <key>aps-environment</key> together with the value node that follows
  // it. In a plist, key and value are sibling nodes — deleting only the key
  // leaves a dangling value and corrupts the file.
  const after = before.replace(
    new RegExp(`\\s*<key>${KEY}</key>\\s*\\n\\s*<[^>]+>[^<]*</[^>]+>`, 'g'),
    '',
  )

  if (after === before) continue

  writeFileSync(file, after)
  changed += 1
  console.log(`[strip-aps] removed ${KEY}: ${file.replace(process.cwd() + '/', '')}`)
}

if (changed === 0) {
  console.log(`[strip-aps] ${KEY} not present — already clean.`)
}
